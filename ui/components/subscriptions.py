"""Tab 4: Tenant Plan & Webhook Simulator.

View tenant plan limits and simulate Stripe ``checkout.session.completed`` events
to test live plan upgrades from Free to Pro.
"""

from __future__ import annotations

import json
from typing import Any
import uuid

import streamlit as st

from ui.api_client import MeteringApiClient


def _default_webhook_payload(event_type: str = "checkout.session.completed") -> dict[str, Any]:
    """Return a synthetic Stripe webhook payload for simulation."""
    if event_type == "checkout.session.completed":
        return {
            "id": f"evt_{uuid.uuid4().hex[:24]}",
            "object": "event",
            "type": event_type,
            "data": {
                "object": {
                    "id": f"cs_{uuid.uuid4().hex[:24]}",
                    "object": "checkout.session",
                    "customer": f"cus_{uuid.uuid4().hex[:24]}",
                    "status": "complete",
                    "payment_status": "paid",
                    "subscription": f"sub_{uuid.uuid4().hex[:24]}",
                    "metadata": {},
                    "created": int(__import__("time").time()),
                    "description": f"Pro plan upgrade for tenant {st.session_state.get('selected_tenant', 'test')}",
                }
            },
            "created": int(__import__("time").time()),
        }
    return {}


def render(api_client: MeteringApiClient) -> None:
    """Render the subscriptions tab content."""
    st.subheader("\U0001f4ca Tenant Plan & Webhook Simulator")

    # ---- Tenant plan viewer ----\
    st.markdown("### Current Plan")

    tenant_slug = st.session_state.get("selected_tenant", "default-tenant")

    with st.spinner("Loading plan details..."):
        try:
            data = api_client.get_tenant_usage(tenant_slug)
            plan = data.get("plan", "free")
            period = data.get("period", "N/A")
            since = data.get("since", "N/A")
            until = data.get("until", "N/A")

            st.info(f"**Plan:** {plan.title()}")
            st.caption(f"Billing period: {period}")
            st.caption(f"Valid from: {since}")
            st.caption(f"Valid until: {until}")

            limit = data.get("plan_limit_microcents", 0)
            used = data.get("total_cost_microcents", 0)
            remaining = data.get("remaining_microcents", 0)

            col_a, col_b, col_c = st.columns(3)
            with col_a:
                st.metric("Monthly Limit", f"${limit / 1_000_000:,.2f}")
            with col_b:
                st.metric("Used", f"${used / 1_000_000:,.2f}")
            with col_c:
                st.metric("Remaining", f"${remaining / 1_000_000:,.2f}")

        except Exception as exc:
            st.error(f"Failed to load plan info: {exc}")

    st.divider()

    # ---- Webhook simulator ----\
    st.markdown("### Simulate Stripe Webhook")

    st.markdown("""
    Simulate a **checkout.session.completed** event to test live plan upgrades from Free to Pro.
    The signature is calculated using the **Stripe secret signing key** from the backend.
    """)

    col_x, col_y = st.columns([1, 1])

    with col_x:
        event_type = st.selectbox(
            "Event Type",
            [
                "checkout.session.completed",
                "customer.subscription.created",
                "customer.subscription.updated",
            ],
            index=0,
        )
        signature = st.text_input(
            "Signature",
            value="t=timestamp,v1=hash_value",
            help="Generated by Stripe; use dummy for simulation",
        )

    with col_y:
        if st.button("🔄 Generate Payload", use_container_width=True):
            st.session_state["webhook_payload"] = json.dumps(
                _default_webhook_payload(event_type), indent=2
            )
            st.rerun()

    # Webhook payload editor
    webhook_payload = st.session_state.get(
        "webhook_payload", json.dumps(_default_webhook_payload(), indent=2)
    )
    payload = st.text_area("Payload (JSON)", value=webhook_payload, height=200)

    col1, col2, col3 = st.columns([1, 1, 1])
    with col1:
        if st.button("🔍 Validate JSON", use_container_width=True):
            try:
                json.loads(payload)
                st.success("✅ Valid JSON")
            except json.JSONDecodeError as e:
                st.error(f"❌ Invalid JSON: {e}")

    with col2:
        if st.button("📤 Trigger Webhook", use_container_width=True, type="primary"):
            with st.spinner("Sending webhook..."):
                try:
                    parsed = json.loads(payload)
                    response = api_client.trigger_stripe_webhook(parsed, signature)
                    st.success("✅ Webhook delivered")
                    st.json(response, expanded=False)
                    # Refresh plan view
                    st.session_state["webhook_triggered"] = True
                    st.rerun()
                except Exception as exc:
                    st.error(f"❌ Webhook failed: {exc}")

    with col3:
        if st.button("🗑️ Clear", use_container_width=True):
            st.session_state.pop("webhook_payload", None)
            st.rerun()

    # Show recent webhook status
    if st.session_state.get("webhook_triggered"):
        st.divider()
        st.caption("✓ Webhook triggered successfully. Plan should now be updated.")
        st.session_state.pop("webhook_triggered", None)
